const withImages = (spot: Omit<StudySpot, "imageUrls" | "seats" | "wifi" | "crowd" | "lastUpdated">): StudySpot => {
  const firstImageIndex = imageIndex % imagePool.length;
  const status = statusCombinations[imageIndex % statusCombinations.length];
  const lastUpdated = lastUpdatedTimes[imageIndex % lastUpdatedTimes.length];
  imageIndex += 1;

  return {
    ...spot,
    ...status,
    lastUpdated,
    imageUrls:
      spotImageOverrides[spot.slug] ??
      Array.from({ length: 4 }, (_, offset) => imagePool[(firstImageIndex + offset) % imagePool.length]),
  };
};

